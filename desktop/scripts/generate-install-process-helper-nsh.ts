import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const DESKTOP_ROOT = path.resolve(import.meta.dir, '..')
export const INSTALL_PROCESS_HELPER_PS1 = path.join(DESKTOP_ROOT, 'build', 'check-install-processes.ps1')
export const INSTALL_PROCESS_HELPER_NSH = path.join(DESKTOP_ROOT, 'build', 'check-install-processes.nsh')

function escapeNsisString(value: string): string {
  return value.replace(/\$/g, '$$$$').replace(/"/g, '$\\"')
}

// NSIS aborts the whole setup when `File` cannot write its payload, and
// security tools commonly block .ps1 writes into %TEMP% (#1486). FileWrite
// only sets the error flag, so the installer can fall back to tasklist.
export function renderInstallProcessHelperNsh(source: string): string {
  // Keep output stable on autocrlf checkouts; PowerShell reads LF scripts.
  const ps1 = source.replace(/\r\n/g, '\n')
  if (!/^[\x0A\x20-\x7E]*$/.test(ps1)) {
    throw new Error('check-install-processes.ps1 must stay ASCII so FileWrite output matches the source')
  }
  const lines = ps1.match(/[^\n]*\n|[^\n]+$/g) ?? []
  const writes = lines.map(line => {
    const text = line.endsWith('\n') ? line.slice(0, -1) : line
    const ending = line.endsWith('\n') ? '$\\n' : ''
    return `    FileWrite $0 "${escapeNsisString(text)}${ending}"`
  })
  return [
    '; Generated by desktop/scripts/generate-install-process-helper-nsh.ts from',
    '; check-install-processes.ps1. Do not edit by hand.',
    '!macro CcHahaWriteInstallProcessHelper _PATH',
    '  Push $0',
    '  ClearErrors',
    '  FileOpen $0 "${_PATH}" w',
    '  ${IfNot} ${Errors}',
    ...writes,
    '    FileClose $0',
    '  ${EndIf}',
    '  Pop $0',
    '!macroend',
    '',
  ].join('\n')
}

if (import.meta.main) {
  writeFileSync(INSTALL_PROCESS_HELPER_NSH, renderInstallProcessHelperNsh(readFileSync(INSTALL_PROCESS_HELPER_PS1, 'utf8')))
  console.log(`Wrote ${path.relative(process.cwd(), INSTALL_PROCESS_HELPER_NSH)}`)
}
