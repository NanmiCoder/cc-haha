import { afterEach, beforeEach, describe, expect, test } from 'bun:test'
import * as fs from 'node:fs/promises'
import * as os from 'node:os'
import * as path from 'node:path'
import {
  claudeUserText,
  defaultHistoryPaths,
  keepProseLines,
  listHistorySources,
  messageTerms,
  scanHistoryTerms,
  type HistoryPaths,
} from './scan.js'

let home: string
let paths: HistoryPaths

beforeEach(async () => {
  home = await fs.mkdtemp(path.join(os.tmpdir(), 'voice-history-'))
  paths = { claudeConfigDir: path.join(home, '.claude'), codexHome: path.join(home, '.codex') }
})

afterEach(async () => {
  await fs.rm(home, { recursive: true, force: true })
})

const user = (content: unknown, extra: Record<string, unknown> = {}) =>
  JSON.stringify({ type: 'user', message: { role: 'user', content }, ...extra })
const assistant = (text: string) =>
  JSON.stringify({ type: 'assistant', message: { role: 'assistant', content: [{ type: 'text', text }] } })

async function writeTranscript(project: string, session: string, lines: string[]) {
  const dir = path.join(paths.claudeConfigDir, 'projects', project)
  await fs.mkdir(dir, { recursive: true })
  await fs.writeFile(path.join(dir, `${session}.jsonl`), lines.join('\n') + '\n', 'utf-8')
}

async function writeCodexHistory(rows: Array<{ session_id?: string; text?: string }>) {
  await fs.mkdir(paths.codexHome, { recursive: true })
  await fs.writeFile(
    path.join(paths.codexHome, 'history.jsonl'),
    rows.map(row => JSON.stringify({ ts: 1, ...row })).join('\n') + '\n',
    'utf-8',
  )
}

describe('which messages count', () => {
  test('only the user\'s own typed text', () => {
    expect(claudeUserText(user('用 Codex 写'))).toBe('用 Codex 写')
    expect(claudeUserText(user([{ type: 'text', text: '第一段 Codex' }, { type: 'image' }, { type: 'text', text: '第二段' }])))
      .toBe('第一段 Codex\n第二段')
    expect(claudeUserText(user([{ type: 'tool_result', content: 'Codex output' }]))).toBeNull()
    expect(claudeUserText(user('Codex', { isMeta: true }))).toBeNull()
    expect(claudeUserText(user('Codex', { isSidechain: true }))).toBeNull()
    expect(claudeUserText(assistant('Codex'))).toBeNull()
    expect(claudeUserText('not json "type":"user"')).toBeNull()
    for (const injected of [
      '<command-name>/clear</command-name>',
      '<local-command-stdout>Codex</local-command-stdout>',
      '<system-reminder>Codex</system-reminder>',
      'Caveat: The messages below were generated by the user while running local commands.',
      '[Request interrupted by user]',
      '<task-notification>Codex</task-notification>',
      '<bash-input>codex</bash-input>',
      'This session is being continued from a previous conversation.',
      '<user-prompt-submit-hook>Codex</user-prompt-submit-hook>',
    ]) {
      expect(claudeUserText(user(injected))).toBeNull()
    }
  })

  test('drops code, URLs, emails and log-like lines before counting', () => {
    const terms = messageTerms([
      '请用 Codex 看一下 `InlineCode` 这里',
      '```ts\nconst FencedCode = 1\n```',
      '参考 https://example.com/UrlTerm 和 dev@MailTerm.com',
      '{"JsonTerm": [1, 2, 3], "x": {"y": "z"}}',
      'at StackTerm (file.ts:10:3)',
      'module.ts:42 FileLineTerm failed',
      'ERROR: LogTerm exploded',
      `LongTerm ${'很长的一行'.repeat(90)}`,
      '还是 Codex，以及 Claude-Code 和 gpt-5.3 the and file',
    ].join('\n'))

    expect([...terms.values()].sort()).toEqual(['Claude-Code', 'Codex', 'gpt-5.3'])
  })

  test('skips whole messages carrying teammate or task envelopes', () => {
    expect(messageTerms('转发 <teammate-message from="a">Codex</teammate-message>').size).toBe(0)
    expect(messageTerms('前文 <task-notification>Codex</task-notification>').size).toBe(0)
  })

  test('keeps prose lines and drops symbol-heavy ones', () => {
    expect(keepProseLines('  正常的一句话 Codex  \n\n=> {a: b, c: d} <=\n123 lines changed')).toEqual(['正常的一句话 Codex'])
  })
})

describe('scanHistoryTerms', () => {
  test('ranks by sessions then messages, once per message, and keeps the most common spelling', async () => {
    await writeTranscript('-work-alpha', 's1', [
      user('用 Codex 和 codex 跑 DeepSeek'),
      user('还是 Codex'),
      assistant('Assistant text never counts: Gemini Gemini'),
    ])
    await writeTranscript('-work-alpha', 's2', [user('Codex 和 DeepSeek')])
    await writeTranscript('-work-beta', 's3', [user('CODEX 与 Gemini')])
    await writeCodexHistory([{ session_id: 'c1', text: 'Gemini 看一下' }])

    const result = await scanHistoryTerms(['claude-code', 'codex'], { paths })

    expect(result.sessions).toBe(4)
    expect(result.messages).toBe(5)
    // < 30 sessions: two sessions are enough.
    expect(result.candidates).toEqual([
      { term: 'Codex', sessions: 3, count: 4 },
      { term: 'DeepSeek', sessions: 2, count: 2 },
      { term: 'Gemini', sessions: 2, count: 2 },
    ])
  })

  test('skips subagent folders and sidechain files, and only reads the chosen sources', async () => {
    await writeTranscript('-work-alpha', 's1', [user('Codex')])
    await writeTranscript('-work-alpha', 's2', [user('Codex')])
    await writeTranscript('-work-alpha', 'agent-1234', [user('Sidechain'), user('Sidechain')])
    const subagents = path.join(paths.claudeConfigDir, 'projects', '-work-alpha', 's1', 'subagents')
    await fs.mkdir(subagents, { recursive: true })
    await fs.writeFile(path.join(subagents, 'agent-1.jsonl'), `${user('Sidechain')}\n`)
    await fs.writeFile(path.join(subagents, 'agent-2.jsonl'), `${user('Sidechain')}\n`)
    await writeCodexHistory([{ session_id: 'c1', text: 'Codex' }, { session_id: 'c2', text: 'Codex' }])

    const claudeOnly = await scanHistoryTerms(['claude-code'], { paths })
    expect(claudeOnly).toEqual({ sessions: 2, messages: 2, candidates: [{ term: 'Codex', sessions: 2, count: 2 }] })
    expect((await scanHistoryTerms(['codex'], { paths })).candidates).toEqual([{ term: 'Codex', sessions: 2, count: 2 }])
  })

  test('needs three sessions once the history has 30 or more', async () => {
    for (let index = 0; index < 30; index += 1) {
      const terms = ['Filler']
      if (index < 3) terms.push('Thrice')
      if (index < 2) terms.push('Twice')
      await writeTranscript('-work', `s${index}`, [user(`用 ${terms.join(' ')}`)])
    }
    const result = await scanHistoryTerms(['claude-code'], { paths })
    expect(result.candidates.map(candidate => candidate.term)).toEqual(['Filler', 'Thrice'])
  })

  test('leaves out terms already in the vocabulary or dismissed, and caps the list', async () => {
    for (const session of ['s1', 's2']) {
      await writeTranscript('-work', session, [user('Codex DeepSeek Gemini Kimi')])
    }
    const result = await scanHistoryTerms(['claude-code'], {
      paths,
      exclude: new Set(['codex', 'gemini']),
      limit: 1,
    })
    expect(result.candidates).toEqual([{ term: 'DeepSeek', sessions: 2, count: 2 }])
  })

  test('missing histories scan as empty', async () => {
    expect(await scanHistoryTerms(['claude-code', 'codex'], { paths })).toEqual({ sessions: 0, messages: 0, candidates: [] })
  })

  test('stops with an AbortError when the request is cancelled', async () => {
    await writeTranscript('-work', 's1', [user('Codex')])
    const controller = new AbortController()
    controller.abort()
    await expect(scanHistoryTerms(['claude-code'], { paths, signal: controller.signal }))
      .rejects.toMatchObject({ name: 'AbortError' })
  })
})

describe('listHistorySources', () => {
  test('counts transcript files and distinct Codex sessions; absent sources are unavailable', async () => {
    expect(await listHistorySources(paths)).toEqual([
      { id: 'claude-code', available: false, sessions: 0 },
      { id: 'codex', available: false, sessions: 0 },
    ])

    await writeTranscript('-work-alpha', 's1', [user('a')])
    await writeTranscript('-work-beta', 's2', [user('b')])
    await writeTranscript('-work-beta', 'agent-x', [user('c')])
    await writeCodexHistory([
      { session_id: 'c1', text: 'a' },
      { session_id: 'c1', text: 'b' },
      { session_id: 'c2', text: 'c' },
      { session_id: 'c3', text: '' },
    ])

    expect(await listHistorySources(paths)).toEqual([
      { id: 'claude-code', available: true, sessions: 2 },
      { id: 'codex', available: true, sessions: 2 },
    ])
  })

  test('default paths follow CLAUDE_CONFIG_DIR and CODEX_HOME', () => {
    const previous = { config: process.env.CLAUDE_CONFIG_DIR, codex: process.env.CODEX_HOME }
    try {
      process.env.CLAUDE_CONFIG_DIR = paths.claudeConfigDir
      process.env.CODEX_HOME = paths.codexHome
      expect(defaultHistoryPaths()).toEqual(paths)
    } finally {
      if (previous.config === undefined) delete process.env.CLAUDE_CONFIG_DIR
      else process.env.CLAUDE_CONFIG_DIR = previous.config
      if (previous.codex === undefined) delete process.env.CODEX_HOME
      else process.env.CODEX_HOME = previous.codex
    }
  })
})
