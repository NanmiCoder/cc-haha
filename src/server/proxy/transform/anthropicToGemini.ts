/**
 * Request transformation: Anthropic Messages → Gemini `generateContent`.
 *
 * OpenCode Go serves its Gemini models only over Google's `generateContent`
 * (`/inference/go/google/v1beta/models/<id>:streamGenerateContent`); every
 * OpenAI and Anthropic path rejects them with `ModelProtocolUnsupported`. The
 * wire shape follows opencode's own Gemini protocol
 * (packages/ai/src/protocols/gemini.ts), which is what that endpoint is built for.
 */

import type { AnthropicContentBlock, AnthropicImageSource, AnthropicRequest } from './types.js'
import { stripLeadingBillingHeader } from './billingHeader.js'
import { documentProvenanceText, searchResultToText } from './anthropicToOpenaiChat.js'
import { normalizeOpenAIReasoningEffort } from './effort.js'
import { toGeminiParametersSchema } from './geminiJsonSchema.js'
import { resolveRequestCompatibility, type RequestCompatibilityOptions } from './requestCompatibility.js'

/**
 * Gemini 3+ rejects a replayed function call without the `thoughtSignature` it
 * was generated with. The CLI keeps `redacted_thinking` data and `thinking`
 * signatures verbatim and replays them to the same model, so signatures travel
 * there behind this prefix; anything else in those fields is not ours to send.
 */
export const GEMINI_THOUGHT_SIGNATURE_PREFIX = 'cc-haha:gemini-thought-signature:v1:'
// Google's documented sentinel for a Gemini 3+ function call whose signature is
// unavailable, such as one generated by another model earlier in the session.
const SKIP_THOUGHT_SIGNATURE_VALIDATOR = 'skip_thought_signature_validator'

export type GeminiInlineData = { inlineData: { mimeType: string; data: string } }

export type GeminiPart = {
  text?: string
  thought?: boolean
  thoughtSignature?: string
  inlineData?: { mimeType: string; data: string }
  functionCall?: { id?: string; name: string; args: Record<string, unknown> }
  functionResponse?: {
    id?: string
    name: string
    response: Record<string, unknown>
    parts?: GeminiInlineData[]
  }
}

export type GeminiContent = { role: 'user' | 'model'; parts: GeminiPart[] }

export type GeminiThinkingLevel = 'low' | 'medium' | 'high'

export type GeminiRequest = {
  contents: GeminiContent[]
  systemInstruction?: { parts: Array<{ text: string }> }
  tools?: Array<{
    functionDeclarations: Array<{
      name: string
      description?: string
      parametersJsonSchema: Record<string, unknown>
    }>
  }>
  toolConfig?: {
    functionCallingConfig: { mode: 'AUTO' | 'ANY' | 'NONE'; allowedFunctionNames?: string[] }
  }
  generationConfig?: {
    maxOutputTokens?: number
    temperature?: number
    topP?: number
    stopSequences?: string[]
    responseMimeType?: string
    responseJsonSchema?: Record<string, unknown>
    thinkingConfig?: { includeThoughts?: boolean; thinkingLevel?: GeminiThinkingLevel }
  }
  /** Resumes a response Gemini split across requests (`finishReason: CONTINUATION`). */
  continuationToken?: string
}

export function encodeGeminiThoughtSignature(signature: string): string {
  return `${GEMINI_THOUGHT_SIGNATURE_PREFIX}${signature}`
}

export function decodeGeminiThoughtSignature(value: unknown): string | undefined {
  if (typeof value !== 'string' || !value.startsWith(GEMINI_THOUGHT_SIGNATURE_PREFIX)) return undefined
  return value.slice(GEMINI_THOUGHT_SIGNATURE_PREFIX.length) || undefined
}

export function anthropicToGemini(
  body: AnthropicRequest,
  options: RequestCompatibilityOptions = {},
): GeminiRequest {
  // Gemini has a single output budget field, so only the resolved number is
  // used; the default-budget omission policy is the same as OpenAI Chat's.
  const compatibility = resolveRequestCompatibility(body, { ...options, protocol: 'openai_chat' })
  const result: GeminiRequest = { contents: convertMessages(body) }

  // The leading billing attribution is dropped: its rotating cch= signature
  // would change the prefix every turn and defeat upstream prompt caching.
  const systemParts = (typeof body.system === 'string' ? [body.system] : (body.system ?? []).map(block => block.text))
    .map(stripLeadingBillingHeader)
    .filter(Boolean)
    .map(text => ({ text }))
  if (systemParts.length > 0) result.systemInstruction = { parts: systemParts }

  const declarations = (body.tools ?? [])
    .filter(tool => tool.name !== 'BatchTool' && tool.input_schema)
    .map(tool => ({
      name: tool.name,
      ...(tool.description ? { description: tool.description } : {}),
      parametersJsonSchema: toGeminiParametersSchema(tool.input_schema),
    }))
  if (declarations.length > 0) {
    result.tools = [{ functionDeclarations: declarations }]
    const toolConfig = convertToolChoice(body.tool_choice, declarations.map(tool => tool.name))
    if (toolConfig) result.toolConfig = toolConfig
  }

  const generationConfig: NonNullable<GeminiRequest['generationConfig']> = {}
  const { outputBudget } = compatibility
  if (outputBudget.field !== 'omit' && outputBudget.effective !== undefined) {
    generationConfig.maxOutputTokens = outputBudget.effective
  }
  if (compatibility.passSamplingParams) {
    if (body.temperature !== undefined) generationConfig.temperature = body.temperature
    if (body.top_p !== undefined) generationConfig.topP = body.top_p
  }
  if (body.stop_sequences?.length) generationConfig.stopSequences = body.stop_sequences
  if (compatibility.structuredOutput) {
    generationConfig.responseMimeType = 'application/json'
    generationConfig.responseJsonSchema = compatibility.structuredOutput.schema
  }
  const thinkingConfig = compatibility.passReasoning ? convertThinking(body) : undefined
  if (thinkingConfig) generationConfig.thinkingConfig = thinkingConfig
  if (Object.keys(generationConfig).length > 0) result.generationConfig = generationConfig

  return result
}

/**
 * Claude Code asks for adaptive thinking plus an effort level. Gemini 3+ takes a
 * thinking level instead of a budget and returns thought summaries only when
 * asked, which is what becomes the visible thinking block.
 */
function convertThinking(body: AnthropicRequest): NonNullable<GeminiRequest['generationConfig']>['thinkingConfig'] {
  const includeThoughts = body.thinking !== undefined && body.thinking.type !== 'disabled'
  const budget = body.thinking?.budget_tokens
  const effort = normalizeOpenAIReasoningEffort(body.output_config?.effort)
    ?? (budget === undefined ? undefined : budget <= 1024 ? 'low' : budget <= 8192 ? 'medium' : 'high')
  const thinkingLevel: GeminiThinkingLevel | undefined = effort === undefined
    ? undefined
    : effort === 'medium' ? 'medium'
      : effort === 'high' || effort === 'xhigh' || effort === 'max' ? 'high'
        : 'low'
  if (!includeThoughts && !thinkingLevel) return undefined
  return {
    ...(includeThoughts ? { includeThoughts: true } : {}),
    ...(thinkingLevel ? { thinkingLevel } : {}),
  }
}

function convertToolChoice(choice: unknown, toolNames: string[]): GeminiRequest['toolConfig'] {
  const value = typeof choice === 'string' ? { type: choice } : choice
  if (value === null || typeof value !== 'object') return undefined
  const { type, name } = value as { type?: unknown; name?: unknown }
  if (type === 'auto') return { functionCallingConfig: { mode: 'AUTO' } }
  if (type === 'any') return { functionCallingConfig: { mode: 'ANY' } }
  if (type === 'none') return { functionCallingConfig: { mode: 'NONE' } }
  if (type === 'tool' && typeof name === 'string' && toolNames.includes(name)) {
    return { functionCallingConfig: { mode: 'ANY', allowedFunctionNames: [name] } }
  }
  return undefined
}

function convertMessages(body: AnthropicRequest): GeminiContent[] {
  const contents: GeminiContent[] = []
  // Gemini answers a call by function name; Anthropic results only carry the id.
  const toolNames = new Map<string, string>()

  for (const message of body.messages) {
    const blocks: AnthropicContentBlock[] = typeof message.content === 'string'
      ? [{ type: 'text', text: message.content }]
      : message.content
    if (message.role === 'assistant') {
      const parts = convertAssistantBlocks(blocks, toolNames)
      if (parts.length > 0) contents.push({ role: 'model', parts })
      continue
    }

    const responses: GeminiPart[] = []
    const others: GeminiPart[] = []
    for (const block of blocks) {
      if (block.type === 'tool_result') responses.push(convertToolResult(block, toolNames))
      else others.push(...convertUserBlock(block))
    }
    // The function-response turn must answer the call turn alone: Gemini rejects
    // one that carries extra parts, so anything else becomes its own user turn.
    if (responses.length > 0) contents.push({ role: 'user', parts: responses })
    if (others.length > 0) contents.push({ role: 'user', parts: others })
  }
  return contents
}

function convertAssistantBlocks(blocks: AnthropicContentBlock[], toolNames: Map<string, string>): GeminiPart[] {
  const parts: GeminiPart[] = []
  let pendingSignature: string | undefined
  // Gemini signs only the first of parallel calls; unsigned siblings are valid.
  let signedCall = false

  for (const block of blocks) {
    if (block.type === 'text') {
      if (block.text) parts.push({ text: block.text })
    } else if (block.type === 'thinking') {
      if (!block.thinking) continue
      const signature = decodeGeminiThoughtSignature(block.signature)
      parts.push({ text: block.thinking, thought: true, ...(signature ? { thoughtSignature: signature } : {}) })
    } else if (block.type === 'redacted_thinking') {
      pendingSignature = decodeGeminiThoughtSignature(block.data) ?? pendingSignature
    } else if (block.type === 'tool_use') {
      toolNames.set(block.id, block.name)
      const signature = pendingSignature ?? (signedCall ? undefined : SKIP_THOUGHT_SIGNATURE_VALIDATOR)
      if (pendingSignature) signedCall = true
      pendingSignature = undefined
      parts.push({
        functionCall: { id: block.id, name: block.name, args: toolInput(block.input) },
        ...(signature ? { thoughtSignature: signature } : {}),
      })
    }
  }
  return parts
}

function toolInput(input: unknown): Record<string, unknown> {
  if (input !== null && typeof input === 'object' && !Array.isArray(input)) return input as Record<string, unknown>
  if (typeof input === 'string') {
    try {
      const parsed = JSON.parse(input) as unknown
      if (parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)) return parsed as Record<string, unknown>
    } catch {
      // A malformed replayed argument string is still a call the model made.
    }
  }
  return {}
}

function convertToolResult(
  block: Extract<AnthropicContentBlock, { type: 'tool_result' }>,
  toolNames: Map<string, string>,
): GeminiPart {
  const content: AnthropicContentBlock[] = typeof block.content === 'string'
    ? [{ type: 'text', text: block.content }]
    : block.content ?? []
  let text = ''
  const media: GeminiInlineData[] = []
  for (const item of content) {
    for (const part of convertUserBlock(item)) {
      // Gemini 3+ accepts images and PDFs nested in the function response itself.
      if (part.inlineData) {
        media.push({ inlineData: part.inlineData })
        continue
      }
      if (!part.text) continue
      // Adjacent text blocks carry no separator on the Anthropic wire; a
      // document or search result starts on its own line.
      const ownLine = item.type !== 'text' && text !== '' && !text.endsWith('\n')
      text += ownLine ? `\n${part.text}` : part.text
    }
  }
  return {
    functionResponse: {
      id: block.tool_use_id,
      name: toolNames.get(block.tool_use_id) ?? block.tool_use_id,
      // Google's documented keys: `output` for a result, `error` for a failure.
      response: block.is_error ? { error: text } : { output: text },
      ...(media.length > 0 ? { parts: media } : {}),
    },
  }
}

function convertUserBlock(block: AnthropicContentBlock): GeminiPart[] {
  switch (block.type) {
    case 'text':
      return block.text ? [{ text: block.text }] : []
    case 'image':
      return [imagePart(block.source)]
    case 'search_result': {
      const text = searchResultToText(block)
      return text ? [{ text }] : []
    }
    case 'document':
      return documentParts(block)
    default:
      return []
  }
}

// Gemini fetches no public URLs: inline data is the only media it accepts here.
function imagePart(source: AnthropicImageSource): GeminiPart {
  if (source.type === 'base64') return { inlineData: { mimeType: source.media_type, data: source.data } }
  if (source.type === 'url') return { text: `[Image: ${source.url}]` }
  return { text: '[Image omitted: file-based image source is not supported by this endpoint.]' }
}

function documentParts(block: Extract<AnthropicContentBlock, { type: 'document' }>): GeminiPart[] {
  const provenance = documentProvenanceText(block)
  const source = block.source
  if (source.type === 'text') return [{ text: `${provenance}${source.data}` }]
  if (source.type === 'base64') {
    return [
      ...(provenance ? [{ text: provenance }] : []),
      { inlineData: { mimeType: source.media_type, data: source.data } },
    ]
  }
  if (source.type === 'content') {
    const parts: GeminiPart[] = provenance ? [{ text: provenance }] : []
    if (typeof source.content === 'string') return [...parts, { text: source.content }]
    for (const item of source.content) {
      parts.push(item.type === 'text' ? { text: item.text } : imagePart(item.source))
    }
    return parts.filter(part => part.inlineData || part.text)
  }
  // The reference already names the document, so only its context is prefixed.
  const contextPrefix = block.context ? `[Document context: ${block.context}]\n` : ''
  const label = block.title ?? (source.type === 'url' ? source.url : 'file')
  return [{
    text: source.type === 'url'
      ? `${contextPrefix}[Document: ${label}](${source.url})`
      : `${contextPrefix}[Document: ${label} omitted — file-based source]`,
  }]
}
