/**
 * Text and summary for approval bases. Only fields that really exist in read-only tool input; unavailable info is not shown.
 */
export type ToolKind = 'command' | 'edit' | 'write' | 'web' | 'read' | 'other'

const EDIT_TOOLS = new Set(['Edit', 'MultiEdit', 'NotebookEdit'])
const READ_TOOLS = new Set(['Read', 'Grep', 'Glob', 'LS', 'NotebookRead'])

export function toolKind(toolName: string): ToolKind {
  if (toolName === 'Bash' || toolName === 'PowerShell') return 'command'
  if (EDIT_TOOLS.has(toolName)) return 'edit'
  // Write May create a new file or overwrite an existing one; the protocol does not distinguish.
  if (toolName === 'Write') return 'write'
  if (toolName === 'WebFetch' || toolName === 'WebSearch') return 'web'
  if (READ_TOOLS.has(toolName)) return 'read'
  return 'other'
}

/** File approvals (Edit/MultiEdit/NotebookEdit/Write) use a taller base and a diff. */
export const isFileChange = (toolName: string) =>
  ['edit', 'write'].includes(toolKind(toolName))

export function approvalTitle(toolName: string) {
  switch (toolKind(toolName)) {
    case 'command':
      return 'Wants to run a command'
    case 'edit':
      return 'Wants to edit files'
    case 'write':
      return 'Wants to write a file'
    case 'web':
      return 'Wants network access'
    case 'read':
      return 'Wants to read files'
    default:
      return `Wants to use ${toolName}`
  }
}

export function denyTitle(toolName: string) {
  switch (toolKind(toolName)) {
    case 'command':
      return 'Do not run this command'
    case 'edit':
      return 'Do not edit this file'
    case 'write':
      return 'Do not write this file'
    case 'web':
      return toolName === 'WebSearch' ? 'Do not do this search' : 'Do not open this web page'
    case 'read':
      return toolName === 'Read' ? 'Do not read this file' : 'Do not do this lookup'
    default:
      return `Do not use ${toolName}`
  }
}

const DENY_VERBS: Record<ToolKind, string> = {
  command: 'run',
  edit: 'change',
  write: 'write',
  web: 'go online',
  read: 'read',
  other: 'use',
}

export function denySuggestions(toolName: string) {
  return [`Explain why you want to ${DENY_VERBS[toolKind(toolName)]} it first`, 'Try a safer approach']
}

/**
 * rule:'always' The server applies the session-level suggestion from the CLI (for Bash the command prefix or full command computed by the computer, 
 * WebFetch a domain, for reads a directory); only when the CLI gives no suggestion is the whole tool allowed. The phone cannot see these suggestions, 
 * so the text only says "similar" without making up a specific prefix.
 */
export function rememberLabel(toolName: string) {
  switch (toolKind(toolName)) {
    case 'command':
      return 'Don’t ask again for similar commands in this session'
    case 'edit':
    case 'write':
      // rule:'always' Let the computer allow per the CLI suggestion: in ask/plan mode switch to auto-accept edits, 
      // and add files outside the workspace to allowed directories; "auto" mode is never downgraded.
      return 'Don’t ask again for similar edits in this session'
    case 'web':
      return toolName === 'WebSearch'
        ? 'Don’t ask again for web searches in this session'
        : 'Don’t ask again for the same site in this session'
    case 'read':
      return 'Don’t ask again for reads in the same location in this session'
    default:
      return `Don’t ask again in this session ${toolName}`
  }
}

const text = (value: unknown) =>
  typeof value === 'string' && value.trim() ? value : undefined

/** Content shown in the base code block: command, path, URL or query; other tools fall back to JSON. */
export function approvalSubject(
  toolName: string,
  input: Record<string, unknown>
): { text: string; prompt?: string } {
  const kind = toolKind(toolName)
  if (kind === 'command' && text(input.command))
    return { text: String(input.command), prompt: '$ ' }
  const value =
    kind === 'edit' || kind === 'write'
      ? (text(input.file_path) ?? text(input.notebook_path))
      : kind === 'web'
        ? (text(input.url) ?? text(input.query))
        : kind === 'read'
          ? (text(input.file_path) ??
            text(input.pattern) ??
            text(input.path) ??
            text(input.notebook_path))
          : undefined
  if (value) return { text: value }
  const json = JSON.stringify(input, null, 2) ?? ''
  return { text: json.length > 600 ? `${json.slice(0, 600)}…` : json }
}

/** One-line summary in the deny state: commands get "$ ", first line only. */
export function denySummary(toolName: string, input: Record<string, unknown>) {
  const subject = approvalSubject(toolName, input)
  const firstLine = subject.text.split('\n')[0] ?? ''
  return `${subject.prompt ?? ''}${firstLine}`
}

/** Bash A self-written description (e.g. "run session transport unit tests") takes priority over the protocol description. */
export function approvalDescription(
  description: string | undefined,
  input: Record<string, unknown>
) {
  return text(description) ?? text(input.description)
}

/** "in ~/code/cc-haha": abbreviate the user home as ~, hidden when the working directory is unavailable. */
export function workDirCaption(workDir?: string | null) {
  const value = workDir?.trim()
  if (!value) return undefined
  const short = value
    .replace(/^\/Users\/[^/]+(?=\/|$)/, '~')
    .replace(/^\/home\/[^/]+(?=\/|$)/, '~')
    .replace(/^[A-Za-z]:\\Users\\[^\\]+(?=\\|$)/, '~')
  return `in ${short}`
}

/** Quick note: fill in directly when the input is empty, otherwise append to the end. */
export function appendSuggestion(current: string, suggestion: string) {
  const trimmed = current.trimEnd()
  if (!trimmed) return suggestion
  if (trimmed.includes(suggestion)) return trimmed
  return /[。！？.!?，,；;：:]$/.test(trimmed)
    ? `${trimmed} ${suggestion}`
    : `${trimmed}. ${suggestion}`
}
