import { expect, test } from 'bun:test'
import {
  appendSuggestion,
  approvalDescription,
  approvalSubject,
  approvalTitle,
  denySuggestions,
  denySummary,
  denyTitle,
  isFileChange,
  rememberLabel,
  toolKind,
  workDirCaption,
} from './decisionCopy'

test('approval titles follow the tool type and fall back to the real tool name', () => {
  expect(approvalTitle('Bash')).toBe('Wants to run a command')
  expect(approvalTitle('PowerShell')).toBe('Wants to run a command')
  for (const tool of ['Edit', 'MultiEdit', 'NotebookEdit'])
    expect(approvalTitle(tool)).toBe('Wants to edit files')
  // Write may create or overwrite; the protocol does not say which.
  expect(approvalTitle('Write')).toBe('Wants to write a file')
  expect(approvalTitle('WebFetch')).toBe('Wants network access')
  expect(approvalTitle('WebSearch')).toBe('Wants network access')
  for (const tool of ['Read', 'Grep', 'Glob'])
    expect(approvalTitle(tool)).toBe('Wants to read files')
  expect(approvalTitle('mcp__github__create_issue')).toBe(
    'Wants to use mcp__github__create_issue'
  )
  expect(isFileChange('Edit')).toBe(true)
  expect(isFileChange('Write')).toBe(true)
  expect(isFileChange('Bash')).toBe(false)
  expect(toolKind('Glob')).toBe('read')
})

test('deny state titles and quick notes name the specific action', () => {
  expect(denyTitle('Bash')).toBe('Do not run this command')
  expect(denyTitle('Edit')).toBe('Do not edit this file')
  expect(denyTitle('Write')).toBe('Do not write this file')
  expect(denyTitle('WebSearch')).toBe('Do not do this search')
  expect(denyTitle('Read')).toBe('Do not read this file')
  expect(denyTitle('Custom')).toBe('Do not use Custom')
  expect(denySuggestions('Bash')).toEqual(['Explain why you want to run it first', 'Try a safer approach'])
  expect(denySuggestions('Edit')[0]).toBe('Explain why you want to change it first')
})

test('remember labels never invent a command prefix the phone cannot see', () => {
  const label = rememberLabel('Bash')
  expect(label).toBe('Don’t ask again for similar commands in this session')
  expect(label).not.toContain('Start')
  expect(rememberLabel('WebFetch')).toBe('Don’t ask again for the same site in this session')
  expect(rememberLabel('Edit')).toBe('Don’t ask again for similar edits in this session')
  expect(rememberLabel('Write')).toBe('Don’t ask again for similar edits in this session')
  expect(rememberLabel('Custom')).toBe('Don’t ask again in this session Custom')
})

test('subjects come from real tool input fields and fall back to JSON', () => {
  expect(approvalSubject('Bash', { command: 'bun test' })).toEqual({
    text: 'bun test',
    prompt: '$ ',
  })
  expect(approvalSubject('Read', { file_path: '/a/b.ts' })).toEqual({
    text: '/a/b.ts',
  })
  expect(approvalSubject('Grep', { pattern: 'TODO', path: 'src' })).toEqual({
    text: 'TODO',
  })
  expect(approvalSubject('WebFetch', { url: 'https://x.dev', prompt: 'p' })).toEqual({
    text: 'https://x.dev',
  })
  expect(approvalSubject('Custom', { a: 1 }).text).toBe('{\n  "a": 1\n}')
  expect(approvalSubject('Custom', { a: 'x'.repeat(900) }).text.length).toBe(601)
  expect(denySummary('Bash', { command: 'git status\ngit diff' })).toBe(
    '$ git status'
  )
  expect(denySummary('Edit', { file_path: 'src/a.ts' })).toBe('src/a.ts')
})

test('description prefers the protocol field and then the Bash description', () => {
  expect(approvalDescription('Server description', { description: 'x' })).toBe('Server description')
  expect(approvalDescription(undefined, { description: 'Run unit tests' })).toBe(
    'Run unit tests'
  )
  expect(approvalDescription('  ', { description: 3 })).toBeUndefined()
})

test('work directory caption abbreviates only the user home and hides when unknown', () => {
  expect(workDirCaption('/Users/me/code/cc-haha')).toBe('in ~/code/cc-haha')
  expect(workDirCaption('/home/dev')).toBe('in ~')
  expect(workDirCaption('C:\\Users\\dev\\repo')).toBe('in ~\\repo')
  expect(workDirCaption('/opt/Users/x')).toBe('in /opt/Users/x')
  expect(workDirCaption('')).toBeUndefined()
  expect(workDirCaption(undefined)).toBeUndefined()
})

test('quick notes fill an empty input or append once to the end', () => {
  expect(appendSuggestion('', 'Try a safer approach')).toBe('Try a safer approach')
  expect(appendSuggestion('Do not run it yet', 'Try a safer approach')).toBe(
    'Do not run it yet. Try a safer approach'
  )
  expect(appendSuggestion('Do not run it yet. ', 'Try a safer approach')).toBe(
    'Do not run it yet. Try a safer approach'
  )
  expect(appendSuggestion('Try a safer approach', 'Try a safer approach')).toBe(
    'Try a safer approach'
  )
})
