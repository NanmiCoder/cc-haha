import { parseConnectionInput, type ParsedConnection } from '../../core/connection'

/** The two methods at the top of the manual connect panel. Which protocol is actually used is still decided by the address itself. */
export type ConnectMode = 'lan' | 'remote'

export const defaultHostName = 'My computer'

function parse(value: string): ParsedConnection | null {
  try {
    return parseConnectionInput(value)
  } catch {
    // The field can be incomplete while the user is typing.
    return null
  }
}

/** What the address in the input parses into; returns null when it cannot be parsed (still typing). */
export function inspectAddress(value: string) {
  const parsed = parse(value)
  if (!parsed) return null
  return {
    auth: parsed.auth,
    hostname: new URL(parsed.url).hostname,
    pairing: Boolean(parsed.pairSecret),
    embeddedCredential: Boolean(parsed.credential),
  }
}

/**
 * Which method the panel should switch to after the address changes: pairing links with #pair= switch to public, 
 * QR codes with LAN credentials switch back to LAN, and anything else keeps the user's current choice.
 */
export function modeForAddress(value: string, current: ConnectMode): ConnectMode {
  const info = inspectAddress(value)
  if (info?.pairing) return 'remote'
  if (info?.embeddedCredential) return 'lan'
  return current
}

/** Content scanned or pasted in: parse failures throw the existing error text directly. */
export function receivedConnection(value: string) {
  const parsed = parseConnectionInput(value)
  return {
    address: value,
    name: new URL(parsed.url).hostname,
    mode: (parsed.auth === 'remote' ? 'remote' : 'lan') as ConnectMode,
  }
}

/** Mask as a password field when the address contains a pairing code or LAN token. */
export function shouldMaskAddress(value: string) {
  return value.includes('#pair=') || value.includes('h5Token=')
}

/** The access token needs to be entered manually only for LAN when the link carries no credentials. */
export function needsToken(mode: ConnectMode, value: string) {
  return mode === 'lan' && !inspectAddress(value)?.embeddedCredential
}

/** When the user's chosen method does not match the address, explain locally first without contacting the computer. */
export function connectionBlocker(mode: ConnectMode, value: string): string {
  const info = inspectAddress(value)
  if (!info) return ''
  if (mode === 'remote' && info.auth === 'lan')
    return 'This is a LAN address. For remote connections paste the HTTPS pairing link generated by the computer, or switch to “Same LAN”.'
  if (mode === 'lan' && info.pairing)
    return 'This is a remote pairing link; switch to “Remote connection” before connecting.'
  return ''
}

export function formFootnote(mode: ConnectMode, value: string) {
  if (mode === 'remote')
    return 'Turn on Cloudflare in “Away connection” on the computer, choose quick connect or fixed domain and scan, then approve on the computer. If the QR code expires or quick connect is rebuilt, scan again.'
  const parsed = parse(value)
  const credential = parsed?.credential
    ? 'The QR code already contains LAN credentials. The phone and computer need to reach each other via this address.'
    : 'The phone needs to reach this address. The token is in Settings → Mobile connection on the computer.'
  if (parsed?.url.startsWith('http:'))
    return `HTTP connections are not encrypted; use only on trusted networks. ${credential}`
  if (parsed?.credential) return credential
  return 'The phone and computer must be on the same network. The token is in Settings → Mobile connection on the computer.'
}

export const addressPlaceholder = (mode: ConnectMode) =>
  mode === 'remote' ? 'https://xxxx.trycloudflare.com/remote#pair=…' : 'http://192.168.1.10:3456'

export const primaryTitle = (mode: ConnectMode) =>
  mode === 'remote' ? 'Request computer authorization' : 'Connection'

/** Monospace capsule on the wait-for-approval page. */
export function remoteBadge(value: string) {
  const info = inspectAddress(value)
  return info ? `Remote · ${info.hostname}` : 'Remote connection'
}

/** Two entries into the connect page: scanning opens by default; "Enter address manually" on the welcome page passes `mode=manual` to open the form directly. */
export type ConnectStage = 'scan' | 'form'

export function initialStage(mode?: string | string[]): ConnectStage {
  const value = Array.isArray(mode) ? mode[0] : mode
  return value === 'manual' ? 'form' : 'scan'
}
