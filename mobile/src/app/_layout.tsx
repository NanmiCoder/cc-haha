import { AppProvider } from '../state/AppContext'
import { LiveActivityBridge } from '../widgets/LiveActivityBridge'
import { PushRegistrationProvider } from '../state/PushRegistrationContext'
import { NotificationBridge } from '../state/NotificationBridge'
import { NotifyPromptHost } from '../state/NotifyPromptHost'
import { DashboardProvider } from '../state/DashboardContext'
import { PreferencesProvider } from '../state/PreferencesContext'
import { useTheme } from '../ui/theme'
import { Platform, View } from 'react-native'
import { useEffect } from 'react'
import { Text } from '../ui/Text'
import { installWebViewport } from '../ui/webKeyboard'
import Constants, { ExecutionEnvironment } from 'expo-constants'

// web Preview: input focus feedback is drawn by the design itself (caret, outline); remove the browser default blue outline.
if (Platform.OS === 'web' && typeof document !== 'undefined') {
  const style = document.createElement('style')
  style.textContent = 'input:focus, textarea:focus { outline: none; }'
  document.head.appendChild(style)
  // App height follows the visible area and shrinks above the soft keyboard when it opens.
  installWebViewport()
}

/** Browser address bar, status bar and page background follow the current appearance, otherwise a light edge shows in dark mode. */
function useWebChromeColor(background: string, dark: boolean) {
  useEffect(() => {
    if (Platform.OS !== 'web' || typeof document === 'undefined') return
    document.querySelector('meta[name="theme-color"]')?.setAttribute('content', background)
    document.documentElement.style.backgroundColor = background
    document.documentElement.style.colorScheme = dark ? 'dark' : 'light'
    document.body.style.backgroundColor = background
  }, [background, dark])
}

function Navigation() {
  const { colors, dark } = useTheme()
  useWebChromeColor(colors.bg, dark)
  const [loaded, error] = useFonts({
    GeistMono: require('../../assets/fonts/GeistMono.ttf'),
  })
  if (!loaded && !error)
    return <View style={{ flex: 1, backgroundColor: colors.bg }} />
  if (
    Platform.OS === 'android' &&
    Constants.executionEnvironment === ExecutionEnvironment.StoreClient
  )
    return (
      <View
        style={{
          flex: 1,
          padding: 30,
          justifyContent: 'center',
          gap: 16,
          backgroundColor: colors.bg,
        }}
      >
        <Text style={{ color: colors.ink, fontSize: 22 }}>
          Please install the cc-haha native App
        </Text>
        <Text style={{ color: colors.ink3, lineHeight: 24 }}>
          Please use a development build or installer generated by the project to enable native connection protection.
        </Text>
      </View>
    )
  return (
    <>
      <NotificationBridge />
      <LiveActivityBridge />
      <NotifyPromptHost />
      <StatusBar style={dark ? 'light' : 'dark'} />
      <Stack
        screenOptions={{
          headerShown: false,
          contentStyle: { backgroundColor: colors.bg },
          animation: 'slide_from_right',
        }}
      >
        <Stack.Screen
          name="connect"
          options={{
            presentation: 'fullScreenModal',
            contentStyle: { backgroundColor: '#121110' },
          }}
        />
        <Stack.Screen
          name="notify"
          options={{
            presentation: 'fullScreenModal',
            animation: 'fade',
            // Can only leave with Continue; no swipe-down or swipe-back dismissal.
            gestureEnabled: false,
          }}
        />
        <Stack.Screen name="new" options={{ presentation: 'modal' }} />
        <Stack.Screen
          name="files"
          options={{
            presentation: 'transparentModal',
            animation: 'none',
            contentStyle: { backgroundColor: 'transparent' },
          }}
        />
      </Stack>
    </>
  )
}
export default function Layout() {
  return (
    <PreferencesProvider>
      <AppProvider>
        <PushRegistrationProvider>
          <DashboardProvider>
            <Navigation />
          </DashboardProvider>
        </PushRegistrationProvider>
      </AppProvider>
    </PreferencesProvider>
  )
}
