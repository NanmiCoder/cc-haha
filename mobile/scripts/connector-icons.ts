/**
 * Rasterize the connector logos shipped with the desktop app (desktop/public/connectors/*.svg) into 96px PNGs, 
 * put them in mobile/assets/connectors/ and generate the static index src/ui/connectorIconSources.ts (Metro needs static require).
 * Rerun after the desktop adds or changes a logo: bun scripts/connector-icons.ts (requires rsvg-convert).
 * Brand marks belong to their services; sources are in desktop/public/connectors/SOURCES.md and imply no endorsement.
 */
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = join(import.meta.dir, '..')
const source = join(root, '..', 'desktop', 'public', 'connectors')
const target = join(root, 'assets', 'connectors')
mkdirSync(target, { recursive: true })

const ids = readdirSync(source)
  .filter((file) => file.endsWith('.svg'))
  .map((file) => file.slice(0, -4))
  .sort()
for (const id of ids)
  execFileSync('rsvg-convert', ['-w', '96', '-h', '96', '-o', join(target, `${id}.png`), join(source, `${id}.svg`)])

const lines = ids.map((id) => `  ${JSON.stringify(id)}: require('../../assets/connectors/${id}.png'),`)
writeFileSync(
  join(root, 'src', 'ui', 'connectorIconSources.ts'),
  `// Generated by scripts/connector-icons.ts, do not edit by hand.\nexport const connectorIconSources: Record<string, number> = {\n${lines.join('\n')}\n}\n`
)
console.log(`${ids.length} connector icons`)
